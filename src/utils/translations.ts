export function translateCondition(description: string, lang: Language): string {
  if (lang === 'en') return description;
  const key = description.trim().toLowerCase();
  if (CONDITION_TRANSLATIONS[key] && CONDITION_TRANSLATIONS[key][lang]) {
    return CONDITION_TRANSLATIONS[key][lang];
  }
  // Fallback matching
  for (const [phrase, dict] of Object.entries(CONDITION_TRANSLATIONS)) {
    if (key.includes(phrase) || phrase.includes(key)) {
      if (dict[lang]) return dict[lang];
    }
  }
  return description;
}
