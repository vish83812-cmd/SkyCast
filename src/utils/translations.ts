/**
 * Returns localized city name in the chosen language (pure regional script when selected)
 */
export function getLocalizedCityName(name: string, lang: Language): string {
  if (lang === 'en') return name;
  const cleanedName = name.replace(/\s*\(.*?\)\s*/g, '').trim();
  const match = Object.keys(CITY_TRANSLITERATIONS).find(
    (k) =>
      k.toLowerCase() === name.toLowerCase() ||
      k.toLowerCase() === cleanedName.toLowerCase() ||
      name.toLowerCase().startsWith(k.toLowerCase()) ||
      cleanedName.toLowerCase().startsWith(k.toLowerCase())
  );
  if (match && CITY_TRANSLITERATIONS[match]) {
    const regional = (CITY_TRANSLITERATIONS[match] as any)[lang];
    if (regional) {
      return regional;
    }
  }
  return name;
}

